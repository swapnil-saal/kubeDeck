import { describe, expect, it } from "vitest";
import { docsPrompt, docsQuestionSchema, relevantSections, siteRelativeLinks, splitDocs } from "@server/ai/docs-answer";

const FULL = `# KubeDeck Docs - Full Context

> Generated by docmd

---

## [Clusters](/web/clusters/) (Web mode)

---
title: "Clusters"
description: "x"
---

# Clusters

Admins add each cluster in Settings → Clusters.

## Add a cluster

Upload a kubeconfig with a token. KubeDeck checks it with kubectl auth whoami.

---

## [Port-forward](/guide/port-forward/) (Guide)

---
title: "Port-forward"
---

# Port-forward

Port-forward works on the desktop only; in web mode the port would open on the server.
`;

describe("the docs chat", () => {
  it("splits the docs export into sections per heading, without front matter, with site-relative links", () => {
    const sections = splitDocs(FULL);
    expect(sections.map((s) => [s.title, s.url])).toEqual([
      ["Clusters", "/web/clusters/"],
      ["Clusters › Add a cluster", "/web/clusters/"],
      ["Port-forward", "/guide/port-forward/"],
    ]);
    expect(sections.some((s) => s.text.includes("title:"))).toBe(false);
  });

  it("answers from the sections that match the question", () => {
    const sections = splitDocs(FULL);
    expect(relevantSections(sections, "how do I add a cluster kubeconfig")[0].title).toBe("Clusters › Add a cluster");
    expect(relevantSections(sections, "port-forward in web mode")[0].title).toBe("Port-forward");
    expect(relevantSections(sections, "the and of")).toEqual([]);
  });

  it("ignores the widget's own search context and tool turns, and keeps the excerpts' links", () => {
    const q = docsQuestionSchema.parse({ message: "add a cluster?\n\n[Documentation Search Context: lots]" });
    expect(q.message).toBe("add a cluster?");
    const prompt = docsPrompt(q.message, [{ sender: "user", text: "hi" }, { sender: "assistant", text: "[Tool Call: search()]" }], splitDocs(FULL).slice(1, 2));
    expect(prompt).toContain("User: hi");
    expect(prompt).not.toContain("Tool Call");
    expect(prompt).toContain("URL: /web/clusters/");
  });

  it("drops a /docs prefix from links, which the widget adds itself", () => {
    expect(siteRelativeLinks("[Groups](/docs/web/groups/) and [Clusters](/docs/web/clusters#add) and [Tempo](https://grafana.com/docs/tempo/)"))
      .toBe("[Groups](/web/groups/) and [Clusters](/web/clusters#add) and [Tempo](https://grafana.com/docs/tempo/)");
  });
});
